import assert from 'node:assert/strict';
import { NextRequest, NextResponse } from 'next/server';
import type { PrismaClient } from '@prisma/client';

export async function checkPlanningApis(args: { db: PrismaClient; clientId: string; advisorId: string; cookie: string; csrfToken: string; request: (path: string, method?: string, body?: unknown, cookie?: string) => NextRequest; record: (message: string) => void }) {
  const { db, clientId, advisorId, cookie, csrfToken, request, record } = args;
  const ctx = { params: Promise.resolve({ id: clientId }) };
  const analysis = await import('../app/api/clients/[id]/analysis/route');
  const reports = await import('../app/api/clients/[id]/reports/route');
  const link = await import('../app/api/reports/[id]/link/route');
  const download = await import('../app/api/reports/[id]/download/route');
  const read = async (response: NextResponse, expected = 200) => { const body = await response.json(); assert.equal(response.status, expected, JSON.stringify(body)); return body; };
  await read(await analysis.GET(request(`/api/clients/${clientId}/analysis`), ctx), 401);
  const first = await read(await analysis.GET(request(`/api/clients/${clientId}/analysis`, 'GET', undefined, cookie), ctx));
  assert.equal(first.snapshot.meta.seed, 42);
  assert.equal(first.snapshot.results.monteCarlo.runs, 5000);
  const second = await read(await analysis.GET(request(`/api/clients/${clientId}/analysis`, 'GET', undefined, cookie), ctx));
  assert.equal(first.id, second.id);
  const parallel = await Promise.all([1, 2].map(() => analysis.GET(request(`/api/clients/${clientId}/analysis`, 'GET', undefined, cookie), ctx).then(response => read(response))));
  assert.equal(parallel[0].id, parallel[1].id);
  const scenarioId = (await db.analysisResult.findUniqueOrThrow({ where: { id: first.id } })).scenarioId;
  assert.equal(await db.analysisResult.count({ where: { scenarioId } }), 1);
  record('Real analysis API calculates sourced results and reuses an unchanged encrypted snapshot');
  const history = await read(await reports.GET(request(`/api/clients/${clientId}/reports`, 'GET', undefined, cookie), ctx));
  const revision = (await db.client.findUniqueOrThrow({ where: { id: clientId } })).revision;
  const body = { requestKey: 'isolated-report-check', sections: history.sections.map((section: { id: string }) => section.id), coverNote: 'Fictional integration fixture only. Not client advice.', letter: history.branding.letter, letterApproved: true, revision, csrfToken };
  await read(await reports.POST(request(`/api/clients/${clientId}/reports`, 'POST', { ...body, letterApproved: false }, cookie), ctx), 422);
  assert.equal(await db.report.count({ where: { clientId } }), 0);
  record('An unapproved advisor letter cannot create or generate a report');
  const generated = await read(await reports.POST(request(`/api/clients/${clientId}/reports`, 'POST', body, cookie), ctx));
  assert.equal(generated.report.status, 'READY', JSON.stringify(generated));
  const same = await read(await reports.POST(request(`/api/clients/${clientId}/reports`, 'POST', body, cookie), ctx));
  assert.equal(same.report.id, generated.report.id);
  assert.equal(await db.report.count({ where: { clientId } }), 1);
  const stored = await db.report.findUniqueOrThrow({ where: { id: generated.report.id } });
  assert.ok(stored.encryptedPdf);
  assert.notEqual(Buffer.from(stored.encryptedPdf!).subarray(0, 5).toString(), '%PDF-');
  assert.equal(stored.sentAt, null);
  record('Approved personalized PDF generation is idempotent, versioned, encrypted and never auto-sent');
  const reportCtx = { params: Promise.resolve({ id: stored.id }) };
  const privateLink = await read(await link.POST(request(`/api/reports/${stored.id}/link`, 'POST', { csrfToken }, cookie), reportCtx));
  const file = await download.GET(request(privateLink.downloadUrl, 'GET', undefined, cookie), reportCtx);
  assert.equal(file.status, 200);
  assert.equal(file.headers.get('content-type'), 'application/pdf');
  const bytes = Buffer.from(await file.arrayBuffer());
  assert.equal(bytes.subarray(0, 5).toString(), '%PDF-');
  await read(await download.GET(request(privateLink.downloadUrl), reportCtx), 401);
  await read(await download.GET(request(`/api/reports/${stored.id}/download?grant=invalid`, 'GET', undefined, cookie), reportCtx), 403);
  const session = await db.advisorSession.findFirstOrThrow({ where: { advisorId, revokedAt: null } });
  const { privateReportLink } = await import('../lib/reports/service');
  const wrongSession = privateReportLink(stored.id, session.id + '-other');
  await read(await download.GET(request(wrongSession, 'GET', undefined, cookie), reportCtx), 403);
  record('PDF downloads require the owning live session and valid expiring grant; wrong-session grants fail');
  const before = stored.encryptedSnapshot;
  const assumptions = await import('../app/api/assumptions/route');
  const settings = await read(await assumptions.GET(request('/api/assumptions', 'GET', undefined, cookie)));
  await read(await assumptions.PATCH(request('/api/assumptions', 'PATCH', { year: settings.assumptions.year, expectedVersion: settings.assumptions.version, edits: { inflation: 0.03 }, csrfToken }, cookie)));
  assert.equal((await db.report.findUniqueOrThrow({ where: { id: stored.id } })).encryptedSnapshot, before);
  const concurrent = await Promise.all([1, 2].map(() => analysis.GET(request(`/api/clients/${clientId}/analysis`, 'GET', undefined, cookie), ctx).then(response => read(response))));
  const refreshed = concurrent[0];
  assert.equal(refreshed.id, concurrent[1].id);
  assert.equal(await db.analysisResult.count({ where: { scenarioId } }), 2);
  assert.notEqual(refreshed.id, first.id);
  record('Advisor assumption changes create a new analysis without changing the previously saved PDF snapshot');
}

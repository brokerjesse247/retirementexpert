import assert from 'node:assert/strict';
import type { PrismaClient } from '@prisma/client';
import { NextRequest, NextResponse } from 'next/server';
import { decryptJson } from '../lib/auth/crypto';
import type { MailPayload } from '../lib/services/email';
import type { IntakeData } from '../lib/intake/schema';

type Harness = { db: PrismaClient; clientId: string; advisorId: string; cookie: string; csrfToken: string; request: (path: string, method?: string, data?: unknown, cookie?: string, trusted?: boolean) => NextRequest; record: (message: string) => void };
export async function checkAnnualReviewApis(h: Harness) {
  const { db, clientId, advisorId, cookie, csrfToken, request, record } = h;
  if (!new URL(process.env.DATABASE_URL!).pathname.endsWith('/retireplan_test')) throw new Error('Annual checks require test-only database.');
  const api = await import('../app/api/clients/[id]/annual-review/route');
  const exchange = await import('../app/api/intake/resume/exchange/route');
  const draftApi = await import('../app/api/intake/draft/route');
  const submit = await import('../app/api/intake/submit/route');
  const { queueDueAnnualReviewReminders } = await import('../lib/annual-review/service');
  const context = { params: Promise.resolve({ id: clientId }) };
  async function body(r: NextResponse, status = 200) { const data = await r.json(); assert.equal(r.status, status, JSON.stringify(data)); return data; }
  await body(await api.GET(request(`/api/clients/${clientId}/annual-review`), context), 401);
  const state = await body(await api.GET(request(`/api/clients/${clientId}/annual-review`, 'GET', undefined, cookie), context));
  await body(await api.POST(request(`/api/clients/${clientId}/annual-review`, 'POST', { action: 'REQUEST_UPDATE', revision: state.client.revision, csrfToken: 'wrong' }, cookie), context), 403);
  const report = await db.report.findFirstOrThrow({ where: { clientId, status: 'READY' } });
  const reportSnapshot = report.encryptedSnapshot; const reportChecksum = report.checksum;
  const now = new Date(); const date = new Date(now.valueOf() + 30 * 86400000).toISOString().slice(0, 10);
  const presented = await body(await api.POST(request(`/api/clients/${clientId}/annual-review`, 'POST', { action: 'PRESENT', reportId: report.id, reviewDate: date, revision: state.client.revision, csrfToken }, cookie), context));
  assert.equal(presented.client.status, 'PRESENTED');
  assert.equal(presented.client.nextReviewDate.slice(0, 10), date);
  record('Only explicit presentation of a ready owned report sets PRESENTED and annual review date');
  await Promise.all([queueDueAnnualReviewReminders(now), queueDueAnnualReviewReminders(now)]);
  assert.equal(await db.reviewDelivery.count({ where: { clientId, kind: 'ADVISOR_REMINDER' } }), 1);
  record('Thirty-day annual reminders are atomically deduplicated under concurrent dispatch');
  const requested = await body(await api.POST(request(`/api/clients/${clientId}/annual-review`, 'POST', { action: 'REQUEST_UPDATE', revision: presented.client.revision, csrfToken }, cookie), context));
  await body(await api.POST(request(`/api/clients/${clientId}/annual-review`, 'POST', { action: 'REQUEST_UPDATE', revision: presented.client.revision, csrfToken }, cookie), context));
  assert.equal(await db.reviewDelivery.count({ where: { clientId, kind: 'UPDATE_REQUEST' } }), 1);
  const delivery = await db.reviewDelivery.findFirstOrThrow({ where: { clientId, kind: 'UPDATE_REQUEST' } });
  const outbox = await db.emailOutbox.findUniqueOrThrow({ where: { id: delivery.outboxId! } });
  assert.equal(outbox.status, 'PENDING');
  const payload = decryptJson<MailPayload>(outbox.encryptedPayload);
  const link = payload.text.match(/https:\/\/[^\s]+/)?.[0]; assert.ok(link);
  const token = new URL(link).searchParams.get('resume'); assert.ok(token);
  const resumed = await exchange.POST(request('/api/intake/resume/exchange', 'POST', { token })); await body(resumed);
  const draftCookie = resumed.cookies.getAll().filter(c => c.value).map(c => `${c.name}=${c.value}`).join('; ');
  await body(await exchange.POST(request('/api/intake/resume/exchange', 'POST', { token })), 400);
  let draft = await body(await draftApi.GET(request('/api/intake/draft', 'GET', undefined, draftCookie)));
  assert.equal(draft.annualUpdate, true); assert.equal(draft.data.consent, false); assert.equal(draft.data.firstName, 'ISOLATED');
  record('Update link is prefilled, one-use, expiring and requires renewed consent; email remains queued');
  const updated = structuredClone(draft.data) as IntakeData; updated.consent = true; updated.expenses.retirementMonthly = '5100';
  draft = await body(await draftApi.PATCH(request('/api/intake/draft', 'PATCH', { data: updated, step: 8, revision: draft.revision, csrfToken: draft.csrfToken }, draftCookie)));
  const submitted = await body(await submit.POST(request('/api/intake/submit', 'POST', { data: updated, revision: draft.revision, csrfToken: draft.csrfToken }, draftCookie)));
  assert.equal(submitted.clientId, clientId); assert.equal(submitted.annualUpdate, true);
  await body(await submit.POST(request('/api/intake/submit', 'POST', { data: updated, revision: draft.revision, csrfToken: draft.csrfToken }, draftCookie)));
  assert.equal(await db.client.count({ where: { advisorId } }), 1);
  const saved = await db.client.findUniqueOrThrow({ where: { id: clientId } });
  assert.equal(saved.status, 'IN_REVIEW'); assert.equal(decryptJson<IntakeData>(saved.encryptedData).expenses.retirementMonthly, '5100');
  const retained = await db.report.findUniqueOrThrow({ where: { id: report.id } });
  assert.equal(retained.encryptedSnapshot, reportSnapshot); assert.equal(retained.checksum, reportChecksum);
  record('Annual submission updates exactly the existing client, is idempotent, and never rewrites prior PDFs');
  assert.equal(await db.emailOutbox.count({ where: { advisorId, status: 'SENT' } }), 0);
}
